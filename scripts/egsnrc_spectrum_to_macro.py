"""Convert an EGSnrc .spectrum file into a Geant4 GPS benchmark macro.

Uses a CITED spectrum (e.g. data/reference/mohan6.spectrum = Mohan, Chui & Lidofsky,
Med Phys 12(5):592-597, 1985, as distributed with EGSnrc) instead of the analytic
make_6mv_spectrum.py beam. This is the scientifically defensible 6 MV source for the
Stage-1 clinical gate.

EGSnrc spectrum format:
  line 1: title
  line 2: NBIN, ENMIN, IMODE
  next NBIN lines: E_upper_i, prob_i   (E_upper = upper energy edge of bin i, MeV;
                   bin i spans [E_upper_{i-1}, E_upper_i], with E_upper_0 = ENMIN)
GPS samples a continuous Arb histogram; we emit bin CENTRES with the bin weights and
linear interpolation -- a faithful continuous approximation of the binned spectrum.
"""
from __future__ import annotations

import argparse
import math

import numpy as np


def parse_egsnrc_spectrum(path):
    with open(path) as f:
        lines = [ln.strip() for ln in f if ln.strip()]
    title = lines[0]
    hdr = [x.strip() for x in lines[1].replace(",", " ").split()]
    nbin, enmin = int(float(hdr[0])), float(hdr[1])
    edges_up, probs = [], []
    for ln in lines[2:2 + nbin]:
        parts = [x for x in ln.replace(",", " ").split() if x]
        edges_up.append(float(parts[0]))
        probs.append(float(parts[1]))
    edges_up = np.asarray(edges_up)
    probs = np.asarray(probs)
    edges_lo = np.concatenate([[enmin], edges_up[:-1]])
    centres = 0.5 * (edges_lo + edges_up)
    return title, centres, probs


def mean_energy(E, w):
    return float((E * w).sum() / w.sum())


def beam_lines(divergent, ssd_cm, surface_z_cm, field_cm):
    """GPS source block.

    Parallel (default): a Plane square source just upstream of the water surface,
    momentum +z. Divergence is then applied post-hoc in Python (inverse-square).

    Divergent: a Point source at SSD from the water surface (z = surface - SSD),
    emitting an `iso` cone whose half-angle atan(field/2 / SSD) reproduces the
    field size at the surface. The cone is rotated to point +z (rot1/rot2 flip
    the GPS angular z' axis to -z, so momentum = -z' = +z for theta=0). Because
    the source physically sits ~SSD away through air, beam divergence AND the
    1/r^2 fall-off are MODELLED by the transport -- no post-hoc correction, and
    no double counting. Requires run.config `world_half_z_cm` large enough
    (>= SSD - surface_z + a few cm) so the source is inside the world.
    """
    if not divergent:
        return [
            "/gps/pos/type Plane",
            "/gps/pos/shape Square",
            "/gps/pos/halfx 5 cm",
            "/gps/pos/halfy 5 cm",
            "/gps/pos/centre 0 0 {:g} cm".format(surface_z_cm - 0.5),
            "/gps/direction 0 0 1",
        ]
    src_z = surface_z_cm - ssd_cm
    half_angle_deg = math.degrees(math.atan((0.5 * field_cm) / ssd_cm))
    return [
        "# DIVERGENT point source: SSD {:g} cm, field {:g} cm at surface,".format(
            ssd_cm, field_cm),
        "# half-angle {:.4f} deg. Circular field (iso cone) ~ the {:g}x{:g}".format(
            half_angle_deg, field_cm, field_cm),
        "# square field for central-axis PDD. Needs world_half_z_cm >= {:g}.".format(
            math.ceil(ssd_cm - surface_z_cm + 5.0)),
        "/gps/pos/type Point",
        "/gps/pos/centre 0 0 {:g} cm".format(src_z),
        "/gps/ang/type iso",
        "/gps/ang/rot1 1 0 0",
        "/gps/ang/rot2 0 -1 0",
        "/gps/ang/mintheta 0 deg",
        "/gps/ang/maxtheta {:.4f} deg".format(half_angle_deg),
    ]


def write_macro(path, title, E, w, nprim, out_dump,
                divergent=False, ssd_cm=100.0, surface_z_cm=-15.0, field_cm=10.0):
    w = w / w.sum()
    geom_note = ("water_box (needs world_half_z_cm >= {:g})".format(
        math.ceil(ssd_cm - surface_z_cm + 5.0)) if divergent else "water_box")
    lines = [
        "# 6 MV benchmark from a CITED spectrum: {}".format(title),
        "# Generated by scripts/egsnrc_spectrum_to_macro.py. Energies in MeV.",
        "# Beam: {}.".format("DIVERGENT point source (SSD modelled)"
                             if divergent else "PARALLEL plane (post-hoc ISF)"),
        "# Run with run.config geometry = {}.".format(geom_note),
        "/run/initialize",
        "",
        "/score/create/boxMesh pdd",
        "/score/mesh/boxSize 2. 2. 15. cm",
        "/score/mesh/nBin 4 4 300",
        "/score/mesh/translate/xyz 0 0 0 cm",
        "/score/quantity/doseDeposit dose Gy",
        "/score/close",
        "",
        "/gps/particle gamma",
    ]
    lines += beam_lines(divergent, ssd_cm, surface_z_cm, field_cm)
    lines += [
        "",
        "/gps/ene/type Arb",
        "/gps/hist/type arb",
    ]
    for e, p in zip(E, w):
        lines.append("/gps/hist/point {:.4f} {:.6e}".format(e, p))
    lines += [
        "/gps/hist/inter Lin",
        "",
        "/run/printProgress {}".format(max(nprim // 20, 1)),
        "/run/beamOn {}".format(nprim),
        "",
        "/score/dumpQuantityToFile pdd dose {}".format(out_dump),
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--spectrum", default="data/reference/mohan6.spectrum")
    ap.add_argument("--nprim", type=int, default=4000000)
    ap.add_argument("--out-macro", default="geant4/macros/benchmark_mohan6.generated.mac")
    ap.add_argument("--out-dump", default="reports/benchmark_mc/pdd_mohan6.txt")
    ap.add_argument("--divergent", action="store_true",
                    help="model a divergent point source at SSD (no post-hoc ISF)")
    ap.add_argument("--ssd-cm", type=float, default=100.0)
    ap.add_argument("--surface-z-cm", type=float, default=-15.0,
                    help="z of the water -z face (default -15 for a 30 cm cube)")
    ap.add_argument("--field-cm", type=float, default=10.0,
                    help="field side at the surface (full width, cm)")
    args = ap.parse_args(argv)

    title, E, w = parse_egsnrc_spectrum(args.spectrum)
    write_macro(args.out_macro, title, E, w, args.nprim, args.out_dump,
                divergent=args.divergent, ssd_cm=args.ssd_cm,
                surface_z_cm=args.surface_z_cm, field_cm=args.field_cm)
    print("Parsed: {}".format(title))
    print("  bins        : {}".format(len(E)))
    print("  energy range: {:.3f} - {:.3f} MeV (centres)".format(E.min(), E.max()))
    print("  mean energy : {:.3f} MeV  (Mohan 6 MV cited ~1.77)".format(
        mean_energy(E, w)))
    print("  macro       -> {}".format(args.out_macro))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
