"""Track B: generate a REPRESENTATIVE 6 MV bremsstrahlung spectrum + GPS macro.

This is NOT a specific commissioned linac and NOT a cited phase-space. It is a
transparent, reproducible analytic spectrum so the Stage-1 benchmark can run a
clinically-shaped 6 MV beam (mean ~1.9 MeV, endpoint 6 MeV) instead of the
mono-energetic 6 MeV beam. For a FORMAL clinical gate, replace with an IAEA 6 MV
phase-space or a cited spectrum (e.g. Mohan et al. 1985) and a measured/BJR-25 PDD.

Model: filtered thick-target bremsstrahlung
    N(E) dE  proportional to  (Emax - E)/E * exp(-c / E^2)     for E in [Elo, Emax]
  - (Emax - E)/E   : Kramers thick-target number spectrum (Kramers 1923).
  - exp(-c / E^2)  : beam-hardening filtration that removes low-energy photons;
                     c is tuned so the fluence-mean energy hits --mean-mev.

Emits a complete GPS macro mirroring benchmark_water.mac (same geometry-agnostic
source/scoring), writing the dose dump to reports/benchmark_mc/pdd_6MV.txt.
"""
from __future__ import annotations

import argparse

import numpy as np


def spectrum(emax, elo, nbins, c):
    E = np.linspace(elo, emax, nbins)
    N = (emax - E) / E * np.exp(-c / E**2)
    N = np.clip(N, 0.0, None)
    s = N.sum()
    return E, (N / s if s > 0 else N)


def mean_energy(E, N):
    return float((E * N).sum() / N.sum())


def tune_c(emax, elo, nbins, target_mean):
    """Bisect the filtration constant c so the mean energy = target_mean."""
    lo, hi = 0.0, 5.0
    for _ in range(60):
        c = 0.5 * (lo + hi)
        E, N = spectrum(emax, elo, nbins, c)
        m = mean_energy(E, N)
        if m < target_mean:   # too soft -> need more filtration (larger c)
            lo = c
        else:
            hi = c
    return 0.5 * (lo + hi)


def write_macro(path, E, N, nprim, out_dump):
    lines = [
        "# REPRESENTATIVE 6 MV bremsstrahlung benchmark (Track B). Generated by",
        "# scripts/make_6mv_spectrum.py -- analytic spectrum, NOT a cited phase-space.",
        "# Energies in MeV. Run with run.config geometry = water_box.",
        "/run/initialize",
        "",
        "/score/create/boxMesh pdd",
        "/score/mesh/boxSize 2. 2. 15. cm",
        "/score/mesh/nBin 4 4 300",
        "/score/mesh/translate/xyz 0 0 0 cm",
        "/score/quantity/doseDeposit dose Gy",
        "/score/close",
        "",
        "/gps/particle gamma",
        "/gps/pos/type Plane",
        "/gps/pos/shape Square",
        "/gps/pos/halfx 5 cm",
        "/gps/pos/halfy 5 cm",
        "/gps/pos/centre 0 0 -15.5 cm",
        "/gps/direction 0 0 1",
        "",
        "/gps/ene/type Arb",
        "/gps/hist/type arb",
    ]
    for e, w in zip(E, N):
        lines.append("/gps/hist/point {:.4f} {:.6e}".format(e, w))
    lines += [
        "/gps/hist/inter Lin",
        "",
        "/run/printProgress {}".format(max(nprim // 20, 1)),
        "/run/beamOn {}".format(nprim),
        "",
        "/score/dumpQuantityToFile pdd dose {}".format(out_dump),
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--emax-mev", type=float, default=6.0)
    ap.add_argument("--elo-mev", type=float, default=0.25)
    ap.add_argument("--nbins", type=int, default=60)
    ap.add_argument("--mean-mev", type=float, default=1.9,
                    help="target fluence-mean energy (typical 6 MV ~1.8-2.0)")
    ap.add_argument("--nprim", type=int, default=2000000)
    ap.add_argument("--out-macro", default="geant4/macros/benchmark_6MV.generated.mac")
    ap.add_argument("--out-dump", default="reports/benchmark_mc/pdd_6MV.txt")
    args = ap.parse_args(argv)

    c = tune_c(args.emax_mev, args.elo_mev, args.nbins, args.mean_mev)
    E, N = spectrum(args.emax_mev, args.elo_mev, args.nbins, c)
    write_macro(args.out_macro, E, N, args.nprim, args.out_dump)

    print("6 MV spectrum: {} bins over [{:.2f}, {:.2f}] MeV".format(
        args.nbins, args.elo_mev, args.emax_mev))
    print("  filtration c   = {:.4f}".format(c))
    print("  mean energy    = {:.3f} MeV  (target {:.2f})".format(
        mean_energy(E, N), args.mean_mev))
    print("  peak at        = {:.3f} MeV".format(float(E[int(np.argmax(N))])))
    print("  macro          -> {}".format(args.out_macro))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
