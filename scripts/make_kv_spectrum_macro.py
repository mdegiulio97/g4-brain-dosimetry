"""Turn a .spectrum file into a Geant4 macro for the
water-box geometry -- a twin of geant4/macros/run_score.mac whose Mono
energy block is replaced by the spectrum's Arb histogram.

Everything else matches run_score.mac verbatim: the same scoring mesh (m,
50x50x300 over 10x10 cm, 1 mm axial), the same parallel 10x10 cm plane source,
and the same G4BAD_NPRIM / G4BAD_OUT env vars -- so a driver script
drives it with the identical run.config (geometry/material/density) path, just
WITHOUT G4BAD_ENERGY (the histogram sets the energy).

Reuses parse_egsnrc_spectrum from scripts/egsnrc_spectrum_to_macro.py so there is
a single spectrum parser in the codebase.

Usage:
  python scripts/make_kv_spectrum_macro.py \
      --spectrum data/reference/kvp120.spectrum \
      --out-macro geant4/macros/run_score_spectrum_kvp120.generated.mac
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from egsnrc_spectrum_to_macro import mean_energy, parse_egsnrc_spectrum  # noqa: E402


def write_macro(path, title, energies_mev, weights):
    w = weights / weights.sum()
    lines = [
        "# kV spectrum macro -- twin of run_score.mac with an Arb",
        "# histogram instead of Mono. Source spectrum: {}".format(title),
        "# Generated by scripts/make_kv_spectrum_macro.py. Energies in MeV.",
        "# Geometry/material/density come from run.config (G4BAD_RUNCONFIG);",
        "# only G4BAD_NPRIM and G4BAD_OUT are read here (no G4BAD_ENERGY).",
        "",
        "/control/getEnv G4BAD_NPRIM",
        "/control/getEnv G4BAD_OUT",
        "",
        "/run/initialize",
        "",
        "# Dose mesh identical to run_score.mac.",
        "/score/create/boxMesh m",
        "/score/mesh/boxSize 5. 5. 15. cm",
        "/score/mesh/nBin 50 50 300",
        "/score/mesh/translate/xyz 0 0 0 cm",
        "/score/quantity/doseDeposit dose Gy",
        "/score/close",
        "",
        "# Parallel square 10x10 cm photon field entering the -z face (z = -15 cm).",
        "/gps/particle gamma",
        "/gps/ene/type Arb",
        "/gps/hist/type arb",
    ]
    for e, p in zip(energies_mev, w):
        lines.append("/gps/hist/point {:.6f} {:.6e}".format(e, p))
    lines += [
        "/gps/hist/inter Lin",
        "/gps/pos/type Plane",
        "/gps/pos/shape Square",
        "/gps/pos/halfx 5 cm",
        "/gps/pos/halfy 5 cm",
        "/gps/pos/centre 0 0 -15.5 cm",
        "/gps/direction 0 0 1",
        "",
        "/run/printProgress 100000",
        "/run/beamOn {G4BAD_NPRIM}",
        "",
        "/score/dumpQuantityToFile m dose {G4BAD_OUT}",
        "",
    ]
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--spectrum", default="data/reference/kvp120.spectrum")
    ap.add_argument("--out-macro",
                    default="geant4/macros/run_score_spectrum_kvp120.generated.mac")
    args = ap.parse_args(argv)

    title, energies, weights = parse_egsnrc_spectrum(args.spectrum)
    write_macro(args.out_macro, title, energies, weights)
    print("Parsed: {}".format(title))
    print("  bins        : {}".format(len(energies)))
    print("  energy range: {:.4f} - {:.4f} MeV (centres)".format(
        energies.min(), energies.max()))
    print("  mean energy : {:.4f} MeV".format(mean_energy(energies, weights)))
    print("  macro       -> {}".format(args.out_macro))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
