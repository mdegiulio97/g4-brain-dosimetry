"""Emit a Geant4 macro whose dose-scoring mesh matches a phantom's voxel grid.

The voxel-phantom mesh dimensions are only known at runtime from the .mha
header, so they cannot be hard-coded in a static macro. This reads the header
(via metaimage_io) and writes a macro with a scoring mesh identical to the
phantom grid, so dose voxel (i,j,k) aligns 1:1 with label voxel (i,j,k).

Energy / primary count / output path are read from environment variables at run
time, exactly like geant4/macros/run_score.mac.

Usage:
  python scripts/make_phantom_score_macro.py \
      --labels data/derived/synthetic/tissue_labels.mha \
      --out geant4/macros/run_phantom.generated.mac
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "python"))
from g4brainatlasdose.metaimage_io import read_metaimage  # noqa: E402

TEMPLATE = """# AUTO-GENERATED by make_phantom_score_macro.py -- do not edit by hand.
# Scoring mesh matches the phantom grid {nx}x{ny}x{nz}, spacing {sx}x{sy}x{sz} mm.
/control/getEnv G4BAD_ENERGY
/control/getEnv G4BAD_NPRIM
/control/getEnv G4BAD_OUT

/run/initialize

/score/create/boxMesh m
/score/mesh/boxSize {hx_mm} {hy_mm} {hz_mm} mm
/score/mesh/nBin {nx} {ny} {nz}
/score/mesh/translate/xyz 0 0 0 mm
/score/quantity/doseDeposit dose Gy
/score/close

/gps/particle gamma
/gps/ene/type Mono
/gps/ene/mono {{G4BAD_ENERGY}}
/gps/pos/type Plane
/gps/pos/shape Square
/gps/pos/halfx {field_hx_mm} mm
/gps/pos/halfy {field_hy_mm} mm
/gps/pos/centre 0 0 {beam_z_mm} mm
/gps/direction 0 0 1

/run/printProgress 100000
/run/beamOn {{G4BAD_NPRIM}}

/score/dumpQuantityToFile m dose {{G4BAD_OUT}}
"""


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", required=True, help="tissue_labels.mha")
    ap.add_argument("--out", required=True)
    ap.add_argument("--field-margin-mm", type=float, default=10.0,
                    help="half-field beyond the phantom transverse extent")
    args = ap.parse_args(argv)

    _, hdr = read_metaimage(args.labels)
    nx, ny, nz = (int(v) for v in hdr["DimSize"].split())
    sx, sy, sz = (float(v) for v in hdr["ElementSpacing"].split())

    hx_mm, hy_mm, hz_mm = nx * sx / 2, ny * sy / 2, nz * sz / 2
    text = TEMPLATE.format(
        nx=nx, ny=ny, nz=nz, sx=sx, sy=sy, sz=sz,
        hx_mm=hx_mm, hy_mm=hy_mm, hz_mm=hz_mm,
        field_hx_mm=hx_mm + args.field_margin_mm,
        field_hy_mm=hy_mm + args.field_margin_mm,
        beam_z_mm=-(hz_mm + 5.0),  # start just outside the -z face
    )
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text, encoding="utf-8")
    print("wrote", args.out, "mesh", (nx, ny, nz))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
